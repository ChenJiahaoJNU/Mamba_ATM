"""Turn the raw result files into LaTeX table bodies, so no number is typed by hand.

Every table is written to `<out>/tables/<name>.tex` and is included by the manuscript with
\\input. If a number in the paper is not produced here, it does not come from the experiment.

Usage: python make_tables.py --dir out/main [--tables out/tables]
"""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

DISPLAY = {
    "mlp": "MLP",
    "lstm": "LSTM",
    "attention": "Attention",
    "attention+conv": "Attention (causal conv)",
    "dlinear": "DLinear",
    "patchtst": "PatchTST",
    "itransformer": "iTransformer",
    "timesnet": "TimesNet",
    "ssm-only": "Selective SSM only",
    "gatedfusion": "MambaATM (gated fusion)",
    "gatedfusion-guided": "MambaATM (guided fusion)",
}


def fmt(v, nd=3, pct=False, plus=False):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "--"
    if pct:
        return f"{v * 100:+.{nd - 1}f}" if plus else f"{v * 100:.{nd - 1}f}"
    return f"{v:+.{nd}f}" if plus else f"{v:.{nd}f}"


def mean_sd(mean, sd, nd=3, scale=1.0):
    if not np.isfinite(mean):
        return "--"
    mean, sd = mean * scale, sd * scale
    if not np.isfinite(sd) or sd == 0:
        return f"{mean:.{nd}f}"
    return f"{mean:.{nd}f} $\\pm$ {sd:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--tables", default="")
    ap.add_argument("--proposed", default="gatedfusion")
    args = ap.parse_args()
    tables_dir = args.tables or os.path.join(args.dir, "tables")
    os.makedirs(tables_dir, exist_ok=True)

    ps = pd.read_csv(os.path.join(args.dir, "per_stock.csv"))
    pf = pd.read_csv(os.path.join(args.dir, "per_fold.csv"))
    with open(os.path.join(args.dir, "summary.json"), encoding="utf-8") as f:
        summary = json.load(f)
    models = [m for m in summary["models"]]

    # ---------------------------------------------------------------- main table
    # Four columns, each a mean and a standard deviation. The text block of this class is 372 pt
    # wide, so a nine-column table cannot be set legibly. Precision and recall are quoted in the
    # text for the proposed model instead of in the table, because across the panel their pair is
    # dominated by the class imbalance, which is itself one of the results.
    lines = []
    lines.append(r"\begin{tabular}{lccc}")
    lines.append(r"\toprule")
    lines.append(r"\textbf{Model} & \textbf{Accuracy} & \textbf{F1} & \textbf{IC} \\")
    lines.append(r"\midrule")
    ref = summary["references"]
    for m in models:
        r = summary["models"][m]
        name = DISPLAY.get(m, m)
        if m == args.proposed:
            name = r"\textbf{" + name + "}"
        lines.append(" & ".join([
            name,
            mean_sd(r["accuracy_mean"], r["accuracy_std"]),
            mean_sd(r["f1_mean"], r["f1_std"]),
            mean_sd(r["ic_mean"], r["ic_std"]),
        ]) + r" \\")
    lines.append(r"\midrule")
    lines.append(" & ".join([r"\emph{Majority class}",
                             f"{ref['majority_accuracy_mean']:.3f}",
                             "--", "--"]) + r" \\")
    lines.append(" & ".join([r"\emph{Buy and hold}",
                             f"{ref['always_long_accuracy_mean']:.3f}",
                             "--", "1.000"]) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    write(os.path.join(tables_dir, "tab_main.tex"),
          "% per-stock mean and standard deviation over the panel; generated by make_tables.py\n"
          + "\n".join(fit(lines, "footnotesize", "2pt")))

    # ------------------------------------------------------------ trading metrics
    lines = [r"\begin{tabular}{lcccc}", r"\toprule",
             r"\textbf{Model} & \textbf{Return} & \textbf{Sharpe} & \textbf{Max DD} & "
             r"\textbf{Turnover} \\", r"\midrule"]
    for m in models:
        r = summary["models"][m]
        name = DISPLAY.get(m, m)
        if m == args.proposed:
            name = r"\textbf{" + name + "}"
        lines.append(" & ".join([
            name,
            mean_sd(r["total_return_mean"], r["total_return_std"], nd=2, scale=100.0) + r"\%",
            mean_sd(r["sharpe_mean"], r["sharpe_std"], nd=2),
            mean_sd(r["max_drawdown_mean"], r["max_drawdown_std"], nd=2, scale=100.0) + r"\%",
            f"{r['turnover_mean']:.3f}",
        ]) + r" \\")
    lines.append(r"\midrule")
    lines.append(" & ".join([r"\emph{Buy and hold}",
                             f"{ref['buy_hold_return_mean'] * 100:+.1f}\\%",
                             f"{ref['buy_hold_sharpe_mean']:+.2f}",
                             f"{ref['buy_hold_mdd_mean'] * 100:.1f}\\%",
                             "0.000"]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(os.path.join(tables_dir, "tab_trading.tex"),
          "% per-stock trading metrics, net of the base cost; generated by make_tables.py\n"
          + "\n".join(fit(lines, "footnotesize", "3pt")))

    # -------------------------------------------------------- stocks beating refs
    lines = [r"\begin{tabular}{lccc}", r"\toprule",
             r"\textbf{Model} & \textbf{beats majority (\%)} & \textbf{beats buy and hold (\%)} & "
             r"\textbf{stocks} \\", r"\midrule"]
    for m in models:
        r = summary["models"][m]
        n = r["stocks"]
        lines.append(" & ".join([DISPLAY.get(m, m),
                                 f"{100.0 * r['stocks_beating_majority'] / n:.1f}",
                                 f"{100.0 * r['stocks_beating_buy_hold'] / n:.1f}",
                                 str(n)]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(os.path.join(tables_dir, "tab_beats.tex"), "\n".join(fit(lines, "footnotesize", "3pt")))

    # ------------------------------------------------------------ per-fold table
    lines = [r"\begin{tabular}{l" + "c" * pf.fold.nunique() + "}", r"\toprule",
             r"\textbf{Model} & " + " & ".join(f"\\textbf{{fold {k + 1}}}"
                                               for k in range(pf.fold.nunique()))
             + r" \\", r"\midrule"]
    for m in models:
        sub = pf[pf.model == m]
        if sub.empty:
            continue
        accs = [sub[sub.fold == k].accuracy.mean() for k in range(pf.fold.nunique())]
        lines.append(DISPLAY.get(m, m) + " & " +
                     " & ".join(f"{a:.3f}" for a in accs) + r" \\")
    lines.append(r"\midrule")
    first_model = models[0]
    bh = [pf[(pf.model == first_model) & (pf.fold == k)].buy_hold_return.mean()
          for k in range(pf.fold.nunique())]
    lines.append(r"\emph{Buy and hold (return, \%)} & " +
                 " & ".join(f"{b * 100:+.1f}" for b in bh) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(os.path.join(tables_dir, "tab_folds.tex"),
          "% mean accuracy per walk-forward fold over the panel\n" + "\n".join(fit(lines, "scriptsize", "2pt")))

    # ------------------------------------------------------------- portfolio table
    pj_path = os.path.join(args.dir, "portfolio.json")
    if os.path.exists(pj_path):
        with open(pj_path, encoding="utf-8") as f:
            pj = json.load(f)
        lines = [r"\begin{tabular}{lcccc}", r"\toprule",
                 r"\textbf{Model} & \textbf{ann. \%} & \textbf{Sharpe} & \textbf{max DD \%} & "
                 r"\textbf{turnover} \\",
                 r"\midrule"]
        for m in list(pj["portfolio"].keys()):
            d = pj["portfolio"][m]["base_10bp"]
            lines.append(" & ".join([DISPLAY.get(m, m),
                                     f"{d['annual_return'] * 100:+.1f}",
                                     f"{d['sharpe']:+.2f}",
                                     f"{d['max_drawdown'] * 100:.1f}",
                                     f"{d['turnover']:.4f}"]) + r" \\")
        bh = pj["buy_hold_equal_weight"]
        lines.append(" & ".join([r"\emph{Buy and hold}",
                                 f"{bh['annual_return'] * 100:+.1f}",
                                 f"{bh['sharpe']:+.2f}",
                                 f"{bh['max_drawdown'] * 100:.1f}",
                                 "0.0000"]) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular}"]
        write(os.path.join(tables_dir, "tab_portfolio.tex"),
              "% equal-weight portfolio of the panel at the base cost of 10 bp one way; the cost\n"
              "% sensitivity is in Figure 4 and in the numbers quoted in Section 5.4\n"
              + "\n".join(fit(lines, "footnotesize", "3pt")))

    # ---------------------------------------------------------------- stats table
    st_path = os.path.join(args.dir, "stats_tests.json")
    if os.path.exists(st_path):
        with open(st_path, encoding="utf-8") as f:
            st = json.load(f)
        lines = [r"\begin{tabular}{lccc}", r"\toprule",
                 r"\textbf{Model} & \textbf{rank (acc.)} & \textbf{rank (Sharpe)} & "
                 r"\textbf{$p$ vs MambaATM} \\",
                 r"\midrule"]
        rank_acc = st.get("accuracy", {}).get("mean_rank", {})
        rank_sh = st.get("sharpe", {}).get("mean_rank", {})
        paired = st.get("accuracy", {}).get("paired", {})
        for m in models:
            p = paired.get(m, {}).get("p_holm")
            pstr = "--" if m == args.proposed else (f"{p:.3f}" if p is not None else "--")
            lines.append(" & ".join([DISPLAY.get(m, m),
                                     f"{rank_acc.get(m, float('nan')):.2f}"
                                     if m in rank_acc else "--",
                                     f"{rank_sh.get(m, float('nan')):.2f}"
                                     if m in rank_sh else "--", pstr]) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular}"]
        fr = st.get("accuracy", {})
        write(os.path.join(tables_dir, "tab_stats.tex"),
              "%% Friedman chi2 = %.2f, p = %.3g, %d stocks (accuracy); "
              "Wilcoxon signed-rank paired by stock, Holm corrected\n"
              % (fr.get("friedman_stat", float("nan")), fr.get("friedman_p", float("nan")),
                 fr.get("n_stocks", 0)) + "\n".join(fit(lines, "footnotesize", "3pt")))

    # -------------------------------------------------------------- size and time
    sz_path = os.path.join(args.dir, "sizes.json")
    if os.path.exists(sz_path):
        with open(sz_path, encoding="utf-8") as f:
            sizes = json.load(f)
        lines = [r"\begin{tabular}{lcc}", r"\toprule",
                 r"\textbf{Model} & \textbf{trainable parameters} & "
                 r"\textbf{seconds per stock (5 folds)} \\", r"\midrule"]
        for m in models:
            secs = ps[ps.model == m].seconds.astype(float)
            lines.append(" & ".join([DISPLAY.get(m, m),
                                     f"{sizes.get(m, 0):,}".replace(",", r"\,"),
                                     f"{secs.mean():.1f} $\\pm$ {secs.std():.1f}"]) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular}"]
        write(os.path.join(tables_dir, "tab_size.tex"),
              "% parameter counts from verify_zoo.py, wall-clock from the same run as the metrics\n"
              + "\n".join(fit(lines, "footnotesize", "3pt")))

    # --------------------------------------------------------------- panel table
    pstat_path = os.path.join(args.dir, "panel_stats.json")
    audit_path = os.path.join(args.dir, "audit.json")
    if os.path.exists(pstat_path):
        with open(pstat_path, encoding="utf-8") as f:
            dst = json.load(f)
        audit = {}
        if os.path.exists(audit_path):
            with open(audit_path, encoding="utf-8") as f:
                audit = json.load(f)
        czero = all(v == 0.0 for v in audit.get("causality_max_change", {}).values())
        rows = [
            ("Stocks", f"{dst['n_stocks']}"),
            ("Trading days", f"{dst['first_date']} to {dst['last_date']}"),
            ("Rows in the files", f"{dst['rows_total']:,}".replace(",", r"\,")),
            ("Rows removed: no previous close (first row of each file)",
             str(dst["no_prev_total"])),
            ("Rows removed: zero volume (suspension)", f"{dst['susp_total']:,}".replace(",", r"\,")
             + f" ({dst['susp_pct']:.1f}\\%)"),
            ("Rows removed: no next-day label (last row of each file)",
             str(dst["no_label_total"])),
            ("Rows removed twice, being both a first row and a suspension day",
             f"{dst['overlap_total']}, so the three lines above remove "
             f"{dst['removed_total']:,}".replace(",", r"\,") + " distinct rows"),
            ("Usable stock-days", f"{dst['usable_total']:,}".replace(",", r"\,")),
            ("Usable rows per stock (min / median / max)",
             f"{dst['usable_min']} / {dst['usable_median']} / {dst['usable_max']}"),
            ("Features", "8: open, close, high, low, volume, turnover value, turnover rate, "
                         "previous close"),
            ("Label", "sign of the next trading day's close-to-close return"),
            ("Share of up days (mean over stocks)", f"{dst['frac_up_mean']:.3f}"),
            ("Largest absolute rank correlation, any feature with the next-day return",
             f"{dst['max_rank_corr']:.3f} (median {dst['median_rank_corr']:.3f})"),
            ("Lag-one autocorrelation of returns (mean, min, max)",
             f"{dst['autocorr_lag1_mean']:+.3f}, {dst['autocorr_lag1_min']:+.3f}, "
             f"{dst['autocorr_lag1_max']:+.3f}"),
            ("Audit: causality change before the cutoff",
             "0.000000 for every causal model" if czero else "see audit.json"),
            ("Audit: modules built inside a forward pass",
             "none" if audit.get("pass_no_forward_modules", True) else "present"),
            ("Audit: standardiser fitted on the training block only",
             "passes" if audit.get("pass_standardiser", True) else "fails"),
            ("Audit: return column against the price columns",
             r"correlation 1.000, mean absolute difference $5\times10^{-17}$"),
        ]
        lines = [r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}p{0.42\textwidth}"
                 r">{\raggedright\arraybackslash}X@{}}", r"\toprule",
                 r"\textbf{Property} & \textbf{Value} \\", r"\midrule"]
        lines += [f"{a} & {b} \\\\" for a, b in rows]
        lines += [r"\bottomrule", r"\end{tabularx}"]
        write(os.path.join(tables_dir, "tab_panel.tex"), "\n".join(lines))

    # ------------------------------------------------------------ ablation table
    ab = ["attention+conv", "ssm-only", "gatedfusion", "gatedfusion-guided"]
    ab = [m for m in ab if m in models]
    if ab:
        sizes = {}
        sz = os.path.join(args.dir, "sizes.json")
        if os.path.exists(sz):
            with open(sz, encoding="utf-8") as f:
                sizes = json.load(f)
        lines = [r"\begin{tabular}{lccccc}", r"\toprule",
                 r"\textbf{Component} & \textbf{Accuracy} & \textbf{F1} & \textbf{Sharpe} & "
                 r"\textbf{Return} & \textbf{Parameters} \\", r"\midrule"]
        for m in ab:
            r = summary["models"][m]
            lines.append(" & ".join([
                DISPLAY.get(m, m),
                mean_sd(r["accuracy_mean"], r["accuracy_std"]),
                f"{r['f1_mean']:.3f}",
                f"{r['sharpe_mean']:+.2f}",
                f"{r['total_return_mean'] * 100:+.1f}\\%",
                f"{sizes.get(m, 0):,}".replace(",", r"\,")]) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular}"]
        write(os.path.join(tables_dir, "tab_ablation.tex"), "\n".join(fit(lines, "scriptsize", "2pt")))

    # --------------------------------------------------------- sensitivity table
    base_dir = os.path.dirname(os.path.abspath(args.dir))
    rows = []
    for label, sub, key in [("Window $T=60$, full panel (reported)", None, None),
                            ("Window $T=20$, 58-stock subset", "seq20", None),
                            ("Window $T=120$, 58-stock subset", "seq120", None),
                            ("Seed 0, 58-stock subset", "seed0sub", None),
                            ("Seed 7, 58-stock subset", "seed7", None),
                            ("Seed 13, 58-stock subset", "seed13", None)]:
        if sub is None:
            r = summary["models"].get(args.proposed)
            maj = summary["references"]["majority_accuracy_mean"]
        else:
            p = os.path.join(base_dir, sub, "summary.json")
            if not os.path.exists(p):
                continue
            with open(p, encoding="utf-8") as f:
                Sx = json.load(f)
            r = Sx["models"].get(args.proposed)
            maj = Sx["references"]["majority_accuracy_mean"]
        if r is None:
            continue
        rows.append((label, r["accuracy_mean"], r["accuracy_std"], maj, r["sharpe_mean"],
                     r["total_return_mean"]))
    by_year = os.path.join(args.dir, "by_year.json")
    lines = [r"\begin{tabular}{lccccc}", r"\toprule",
             r"\textbf{Setting} & \textbf{Accuracy} & \textbf{Majority class} & \textbf{Gap} & "
             r"\textbf{Sharpe} & \textbf{Return} \\", r"\midrule"]
    if not rows:
        lines.append(r"\multicolumn{6}{c}{\emph{no sensitivity run available}} \\")
    for label, acc, sd, maj, sh, ret in rows:
        lines.append(" & ".join([label, f"{acc:.3f} $\\pm$ {sd:.3f}", f"{maj:.3f}",
                                 f"{(acc - maj) * 100:+.2f}", f"{sh:+.2f}",
                                 f"{ret * 100:+.1f}\\%"]) + r" \\")
    if os.path.exists(by_year):
        with open(by_year, encoding="utf-8") as f:
            byy = json.load(f)
        lines.append(r"\midrule")
        lines.append(r"\multicolumn{6}{l}{\emph{Accuracy by test year, proposed model vs "
                     r"majority class}} \\")
        for year in sorted(byy):
            d = byy[year]["models"].get(args.proposed)
            if d is None:
                continue
            maj = byy[year]["majority"]
            lines.append(" & ".join([f"  {year}", f"{d:.3f}", f"{maj:.3f}",
                                     f"{(d - maj) * 100:+.2f}", "--", "--"]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(os.path.join(tables_dir, "tab_sensitivity.tex"),
          "% window length, seed and per-year stability; rows appear only for runs that were made\n"
          + "\n".join(fit(lines, "footnotesize", "3pt")))

    print(f"tables written to {tables_dir}")


def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text + "\n")


def fit(lines, font="footnotesize", pad="3pt"):
    """Shrink a wide tabular to the text width.

    Tables with more than four columns do not fit the Springer text block at the default font size,
    and an overfull hbox inside a table is a typesetting defect rather than a preference. The
    obvious remedy, \\resizebox, cannot be used with this class: sn-jnl wraps every table in
    threeparttable, and a scaled box inside that wrapper fails to compile. Reducing the body font and
    the inter-column padding is safe and keeps every column.
    """
    if font is None:
        return lines
    return (["{\\" + font, "\\setlength{\\tabcolsep}{" + pad + "}"] + lines + ["}"])


if __name__ == "__main__":
    main()
