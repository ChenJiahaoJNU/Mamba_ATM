"""Emit numbers.tex: every quantity the manuscript quotes in prose, as a LaTeX macro.

The manuscript never contains a typed number that also appears in a table. This script reads the
result files and writes one macro per quantity, so a rerun of the experiment cannot leave the text
and the tables disagreeing, which is one of the defects the review identified.

Usage: python emit_numbers.py --dir out/main --panel <panel dir> --out <rework dir>/numbers.tex
"""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

PROPOSED = "gatedfusion"
GUIDED = "gatedfusion-guided"
DISPLAY = {
    "mlp": "MLP", "lstm": "LSTM", "attention": "attention",
    "attention+conv": "attention with a causal convolution", "dlinear": "DLinear",
    "patchtst": "PatchTST", "itransformer": "iTransformer", "timesnet": "TimesNet",
    "ssm-only": "the selective SSM branch alone", "gatedfusion": "MambaATM",
    "gatedfusion-guided": "MambaATM with guided modulation",
}


def mac(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--panel", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--audit", default="")
    args = ap.parse_args()

    with open(os.path.join(args.dir, "summary.json"), encoding="utf-8") as f:
        S = json.load(f)
    ps = pd.read_csv(os.path.join(args.dir, "per_stock.csv"))
    pj = {}
    pj_path = os.path.join(args.dir, "portfolio.json")
    if os.path.exists(pj_path):
        with open(pj_path, encoding="utf-8") as f:
            pj = json.load(f)
    st = {}
    st_path = os.path.join(args.dir, "stats_tests.json")
    if os.path.exists(st_path):
        with open(st_path, encoding="utf-8") as f:
            st = json.load(f)
    with open(os.path.join(args.dir, "sizes.json"), encoding="utf-8") as f:
        sizes = json.load(f)

    M = S["models"]
    ref = S["references"]
    others = [m for m in M if m != PROPOSED]
    acc_best = max(M, key=lambda m: M[m]["accuracy_mean"])
    sh_best = max(M, key=lambda m: M[m]["sharpe_mean"])
    port_best = (max(pj["portfolio"], key=lambda m: pj["portfolio"][m]["base_10bp"]["sharpe"])
                 if pj else acc_best)

    out = []
    out.append("% generated by emit_numbers.py -- do not edit by hand")
    out.append(mac("nStocks", len(ps.stock.unique())))
    out.append(mac("nModels", len(M)))
    out.append(mac("nFolds", int(S["config"]["folds"])))
    out.append(mac("seqLen", int(S["config"]["seq"])))
    out.append(mac("nEpochs", int(S["config"]["epochs"])))
    out.append(mac("seedUsed", int(S["config"]["seed"])))
    out.append(mac("runMinutes", f"{S.get('minutes', 0):.0f}"))

    # ---------------- dataset
    stats_path = os.path.join(args.dir, "panel_stats.json")
    if os.path.exists(stats_path):
        with open(stats_path, encoding="utf-8") as f:
            dst = json.load(f)
    else:
        files = sorted(f for f in os.listdir(args.panel) if f.endswith(".csv"))
        rows = []
        for f in files:
            df = pd.read_csv(os.path.join(args.panel, f), encoding="utf-8-sig")
            df.columns = [c.strip() for c in df.columns]
            ret = pd.to_numeric(df["涨跌幅"], errors="coerce")
            vol = pd.to_numeric(df["成交量"], errors="coerce")
            rows.append({"rows": len(df), "usable": int((ret.notna() & (vol > 0)).sum()),
                         "susp": int((vol == 0).sum()), "first": str(df["日期"].iloc[0]),
                         "last": str(df["日期"].iloc[-1]),
                         "no_prev_close": int(ret.isna().sum()),
                         "no_label": int(ret.shift(-1).isna().sum()),
                         "no_prev_and_susp": int((ret.isna() & (vol == 0)).sum())})
        d = pd.DataFrame(rows)
        dst = {"n_stocks": len(d), "rows_total": int(d.rows.sum()),
               "usable_total": int(d.usable.sum()), "susp_total": int(d.susp.sum()),
               "susp_pct": 100.0 * d.susp.sum() / d.rows.sum(), "usable_min": int(d.usable.min()),
               "usable_median": int(d.usable.median()), "first_date": d["first"].mode()[0],
               "no_prev_total": int(d.no_prev_close.sum()),
               "no_label_total": int(d.no_label.sum()),
               "overlap_total": int(d.no_prev_and_susp.sum()),
               "removed_total": int(d.rows.sum() - d.usable.sum()),
               "last_date": d["last"].mode()[0], "max_rank_corr": float("nan"),
               "median_rank_corr": float("nan"), "autocorr_lag1_mean": float("nan"),
               "autocorr_lag1_min": float("nan"), "autocorr_lag1_max": float("nan")}
    out.append(mac("nPanelRows", f"{dst['rows_total']:,}".replace(",", r"\,")))
    out.append(mac("nDays", f"{dst.get('n_dates', 0):,}".replace(",", r"\,")))
    out.append(mac("nStockDays", f"{dst['usable_total']:,}".replace(",", r"\,")))
    out.append(mac("nSuspDays", f"{dst['susp_total']:,}".replace(",", r"\,")))
    out.append(mac("pctSusp", f"{dst['susp_pct']:.1f}\\%"))
    out.append(mac("nNoPrevRows", dst.get("no_prev_total", dst["n_stocks"])))
    out.append(mac("nNoLabelRows", dst.get("no_label_total", dst["n_stocks"])))
    out.append(mac("nOverlapRows", dst.get("overlap_total", 0)))
    out.append(mac("nRemovedRows", f"{dst.get('removed_total', 0):,}".replace(",", r"\,")))
    out.append(mac("firstDate", dst["first_date"]))
    out.append(mac("lastDate", dst["last_date"]))
    out.append(mac("minRows", dst["usable_min"]))
    out.append(mac("medRows", dst["usable_median"]))
    out.append(mac("maxRows", dst.get("usable_max", dst["usable_median"])))
    out.append(mac("maxRankCorr", f"{dst['max_rank_corr']:.3f}"))
    out.append(mac("medRankCorr", f"{dst['median_rank_corr']:.3f}"))
    out.append(mac("acfMean", f"{dst['autocorr_lag1_mean']:+.3f}"))
    out.append(mac("acfMin", f"{dst['autocorr_lag1_min']:+.3f}"))
    out.append(mac("acfMax", f"{dst['autocorr_lag1_max']:+.3f}"))
    out.append(mac("nFeatures", 8))

    # ---------------- references
    out.append(mac("accMaj", f"{ref['majority_accuracy_mean']:.3f}"))
    out.append(mac("accLong", f"{ref['always_long_accuracy_mean']:.3f}"))
    out.append(mac("retBH", f"{ref['buy_hold_return_mean'] * 100:+.1f}\\%"))
    out.append(mac("shBH", f"{ref['buy_hold_sharpe_mean']:+.2f}"))
    out.append(mac("ddBH", f"{ref['buy_hold_mdd_mean'] * 100:.1f}\\%"))
    out.append(mac("medRetBH", f"{ref['buy_hold_return_median'] * 100:+.1f}\\%"))

    # ---------------- proposed model
    p = M[PROPOSED]
    out.append(mac("accProp", f"{p['accuracy_mean']:.3f}"))
    out.append(mac("accPropSd", f"{p['accuracy_std']:.3f}"))
    out.append(mac("precProp", f"{p['precision_mean']:.3f}"))
    out.append(mac("recallProp", f"{p['recall_mean']:.3f}"))
    out.append(mac("icProp", f"{p['ic_mean']:+.4f}"))
    out.append(mac("shProp", f"{p['sharpe_mean']:+.2f}"))
    out.append(mac("ddProp", f"{p['max_drawdown_mean'] * 100:.1f}\\%"))
    out.append(mac("retProp", f"{p['total_return_mean'] * 100:+.1f}\\%"))
    out.append(mac("retPropSd", f"{p['total_return_std'] * 100:.1f}\\%"))
    out.append(mac("turnProp", f"{p['turnover_mean']:.3f}"))
    out.append(mac("beatMajProp", f"{100.0 * p['stocks_beating_majority'] / p['stocks']:.0f}\\%"))
    out.append(mac("beatBHProp", f"{100.0 * p['stocks_beating_buy_hold'] / p['stocks']:.0f}\\%"))

    # ---------------- other models
    for key, name in [("accMLP", "mlp"), ("accLSTM", "lstm"), ("accAtt", "attention+conv"),
                      ("accDLinear", "dlinear"), ("accPatch", "patchtst"),
                      ("accITrans", "itransformer"), ("accTimes", "timesnet"),
                      ("accSSM", "ssm-only"), ("accGuided", GUIDED)]:
        r = M[name]
        out.append(mac(key, f"{r['accuracy_mean']:.3f}"))
        out.append(mac(key + "Sd", f"{r['accuracy_std']:.3f}"))
    out.append(mac("accBest", f"{M[acc_best]['accuracy_mean']:.3f}"))
    out.append(mac("accBestName", DISPLAY.get(acc_best, acc_best)))
    second_best = max(others, key=lambda m: M[m]["accuracy_mean"])
    out.append(mac("accSecond", f"{M[second_best]['accuracy_mean']:.3f}"))
    out.append(mac("accSecondName", DISPLAY.get(second_best, second_best)))
    out.append(mac("accWorst", f"{min(M[m]['accuracy_mean'] for m in M):.3f}"))
    out.append(mac("shBest", f"{M[sh_best]['sharpe_mean']:+.2f}"))
    out.append(mac("shBestName", DISPLAY.get(sh_best, sh_best)))
    out.append(mac("retBest", f"{M[acc_best]['total_return_mean'] * 100:+.1f}\\%"))
    out.append(mac("rangeAcc", f"{(max(M[m]['accuracy_mean'] for m in M) - min(M[m]['accuracy_mean'] for m in M)) * 100:.1f}"))
    f1_best = max(M, key=lambda m: M[m]["f1_mean"])
    out.append(mac("fOneBest", f"{M[f1_best]['f1_mean']:.3f}"))
    out.append(mac("fOneBestName", DISPLAY.get(f1_best, f1_best)))
    majbest = max(M, key=lambda m: M[m]["stocks_beating_majority"] / M[m]["stocks"])
    out.append(mac("beatMajBest", f"{100.0 * M[majbest]['stocks_beating_majority'] / M[majbest]['stocks']:.1f}\\%"))
    out.append(mac("beatMajBestName", DISPLAY.get(majbest, majbest)))

    # ---------------- ablation contrasts
    out.append(mac("accGuidedMinusPlain",
                   f"{(M[GUIDED]['accuracy_mean'] - M[PROPOSED]['accuracy_mean']) * 100:+.2f}"))
    out.append(mac("shGuided", f"{M[GUIDED]['sharpe_mean']:+.2f}"))
    out.append(mac("shGuidedMinusPlain",
                   f"{M[GUIDED]['sharpe_mean'] - M[PROPOSED]['sharpe_mean']:+.2f}"))
    out.append(mac("paramProposed", f"{sizes.get(PROPOSED, 0):,}".replace(",", r"\,")))
    out.append(mac("paramGuided", f"{sizes.get(GUIDED, 0):,}".replace(",", r"\,")))
    out.append(mac("paramSSM", f"{sizes.get('ssm-only', 0):,}".replace(",", r"\,")))
    out.append(mac("paramPatch", f"{sizes.get('patchtst', 0):,}".replace(",", r"\,")))
    out.append(mac("paramMLP", f"{sizes.get('mlp', 0):,}".replace(",", r"\,")))
    out.append(mac("paramDLinear", f"{sizes.get('dlinear', 0):,}".replace(",", r"\,")))

    # ---------------- timing
    sec = ps.groupby("model").seconds.mean().to_dict()
    turn = ps.groupby("model").turnover.mean().to_dict()
    turn_best = max(turn, key=turn.get) if turn else PROPOSED
    out.append(mac("turnBest", f"{turn.get(turn_best, 0):.3f}"))
    out.append(mac("turnBestName", DISPLAY.get(turn_best, turn_best)))
    out.append(mac("secProposed", f"{sec.get(PROPOSED, 0):.0f}"))
    out.append(mac("secPatch", f"{sec.get('patchtst', 0):.0f}"))
    out.append(mac("secMLP", f"{sec.get('mlp', 0):.0f}"))
    out.append(mac("secLSTM", f"{sec.get('lstm', 0):.0f}"))
    out.append(mac("secAtt", f"{sec.get('attention+conv', 0):.0f}"))

    # ---------------- portfolio
    if pj:
        bh = pj["buy_hold_equal_weight"]
        out.append(mac("portDays", pj["days"]))
        out.append(mac("portBreadth", f"{pj['portfolio'][PROPOSED]['avg_breadth']:.0f}"))
        out.append(mac("portAnnBH", f"{bh['annual_return'] * 100:+.1f}\\%"))
        out.append(mac("portShBH", f"{bh['sharpe']:+.2f}"))
        out.append(mac("portDDBH", f"{bh['max_drawdown'] * 100:.1f}\\%"))
        out.append(mac("portTotalBH", f"{bh['total_return'] * 100:+.0f}\\%"))
        for lab, key in [("", "base_10bp"), ("Low", "low_6bp"), ("High", "high_15bp"),
                         ("Zero", "zero")]:
            if key not in pj["portfolio"][PROPOSED]:
                continue
            d = pj["portfolio"][PROPOSED][key]
            out.append(mac(f"portAnnProp{lab}", f"{d['annual_return'] * 100:+.1f}\\%"))
            out.append(mac(f"portShProp{lab}", f"{d['sharpe']:+.2f}"))
            out.append(mac(f"portDDProp{lab}", f"{d['max_drawdown'] * 100:.1f}\\%"))
            out.append(mac(f"portTurnProp{lab}", f"{d['turnover']:.2f}"))
        d = pj["portfolio"][port_best]["base_10bp"]
        out.append(mac("portBestName", DISPLAY.get(port_best, port_best)))
        out.append(mac("portAnnBest", f"{d['annual_return'] * 100:+.1f}\\%"))
        out.append(mac("portShBest", f"{d['sharpe']:+.2f}"))
        out.append(mac("portDDBest", f"{d['max_drawdown'] * 100:.1f}\\%"))
        n_beat = sum(1 for m in pj["portfolio"]
                     if pj["portfolio"][m]["base_10bp"]["sharpe"] > bh["sharpe"])
        out.append(mac("nPortBeatBH", n_beat))
        profit = [m for m in pj["portfolio"]
                  if pj["portfolio"][m]["base_10bp"]["annual_return"] > 0]
        out.append(mac("nPortProfit", len(profit)))
        out.append(mac("portProfitNames",
                       ", ".join(sorted(DISPLAY.get(m, m) for m in profit))))

    # ---------------- statistics
    if st:
        fa, fs = st.get("accuracy", {}), st.get("sharpe", {})
        out.append(mac("friedmanAcc", f"{fa.get('friedman_stat', float('nan')):.1f}"))
        out.append(mac("friedmanAccP", f"{fa.get('friedman_p', float('nan')):.2g}"))
        out.append(mac("friedmanSh", f"{fs.get('friedman_stat', float('nan')):.1f}"))
        out.append(mac("friedmanShP", f"{fs.get('friedman_p', float('nan')):.2g}"))
        out.append(mac("rankPropAcc", f"{fa.get('mean_rank', {}).get(PROPOSED, float('nan')):.2f}"))
        out.append(mac("rankPropSh", f"{fs.get('mean_rank', {}).get(PROPOSED, float('nan')):.2f}"))
        out.append(mac("rankBestAccName",
                       DISPLAY.get(min(fa.get("mean_rank", {"x": 0}), key=fa["mean_rank"].get),
                                   "x")))
        paired = fa.get("paired", {})
        sig = [m for m in paired if paired[m]["significant_5pct"]]
        out.append(mac("nSignificantVsProp", len(sig)))
        out.append(mac("nCompared", len(paired)))
        p_best = min([paired[m]["p_holm"] for m in paired], default=float("nan"))
        out.append(mac("pMinVsProp", f"{p_best:.3g}"))
        beats = [m for m in sig if paired[m]["mean_diff"] > 0]
        loses = [m for m in sig if paired[m]["mean_diff"] < 0]
        out.append(mac("accBeatsName",
                       ", ".join(DISPLAY.get(m, m) for m in beats) if beats else "none"))
        out.append(mac("accLosesToName",
                       ", ".join(DISPLAY.get(m, m) for m in loses) if loses else "none"))

    # ---------------- derived contrasts
    second = max(M[m]["accuracy_mean"] for m in others)
    out.append(mac("nAccLead", f"{(M[PROPOSED]['accuracy_mean'] - second) * 100:+.2f}"))
    branch_best = max(M["attention+conv"]["accuracy_mean"], M["ssm-only"]["accuracy_mean"])
    out.append(mac("nGateGain", f"{(M[PROPOSED]['accuracy_mean'] - branch_best) * 100:+.2f}"))
    out.append(mac("secRatio", f"{sec.get(PROPOSED, 0) / max(sec.get('mlp', 1), 1e-9):.1f}"))
    if pj and "zero" in pj["portfolio"].get(PROPOSED, {}):
        out.append(mac("shPropZero", f"{pj['portfolio'][PROPOSED]['zero']['sharpe']:+.2f}"))
    else:
        out.append(mac("shPropZero", "--"))

    # ---------------- sensitivity runs, present only when they have been run
    sens = {"T20": "seq20", "T120": "seq120"}
    seed_runs = ["seed0sub", "seed7", "seed13"]
    base = os.path.dirname(os.path.abspath(args.dir))
    accs, majs, seed_accs = [], [], []
    for tag, sub in sens.items():
        p = os.path.join(base, sub, "summary.json")
        if not os.path.exists(p):
            continue
        with open(p, encoding="utf-8") as f:
            Sx = json.load(f)
        if PROPOSED not in Sx.get("models", {}):
            continue
        a = Sx["models"][PROPOSED]["accuracy_mean"]
        mj = Sx["references"]["majority_accuracy_mean"]
        # no per-run macros: LaTeX control sequences cannot contain digits, and the manuscript only
        # quotes the range across the runs
        accs.append(a)
        majs.append(mj)
    for sub in seed_runs:
        p = os.path.join(base, sub, "summary.json")
        if not os.path.exists(p):
            continue
        with open(p, encoding="utf-8") as f:
            Sx = json.load(f)
        if PROPOSED in Sx.get("models", {}):
            seed_accs.append(Sx["models"][PROPOSED]["accuracy_mean"])
    if accs:
        out.append(mac("accTMin", f"{min(accs):.3f}"))
        out.append(mac("accTMax", f"{max(accs):.3f}"))
        out.append(mac("accMajTMin", f"{min(majs):.3f}"))
        out.append(mac("accMajTMax", f"{max(majs):.3f}"))
    else:
        for k in ("accTMin", "accTMax", "accMajTMin", "accMajTMax"):
            out.append(mac(k, "--"))
    if seed_accs:
        all_seeds = seed_accs + [M[PROPOSED]["accuracy_mean"]]
        out.append(mac("accSeedSd", f"{(max(all_seeds) - min(all_seeds)) * 100:.2f}"))
    else:
        out.append(mac("accSeedSd", "--"))

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {len(out)} macros to {args.out}")
    for line in out[:12]:
        print("  " + line)


if __name__ == "__main__":
    main()
